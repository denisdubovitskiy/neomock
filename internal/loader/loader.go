// Package loader загружает интерфейсы из исходных пакетов через go/packages
// и строит model.Interface (DESIGN §3.2, §3.3).
// Зависимость: golang.org/x/tools/go/packages (генератор, не рантайм).
package loader

import (
	"bufio"
	"fmt"
	"go/ast"
	"go/token"
	"go/types"
	"os"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"

	"github.com/denisdubovitskiy/neomock/internal/model"
)

// Режимы источника (§3.3): где искать интерфейс.
const (
	SourceGo   = "go"   // только GoFiles
	SourceTest = "test" // только *_test.go (включая внешний foo_test)
	SourceAll  = "all"  // оба с дедупом
)

// GeneratedMarker — маркер сгенерированных neomock файлов (§3.3): такие файлы
// исключаются из поиска и селекции интерфейсов.
const GeneratedMarker = "Code generated by neomock DO NOT EDIT"

// directiveDisable — директива исключения интерфейса (§4.5).
const directiveDisable = "neomock:generate=false"

// Config параметры загрузки одного интерфейса.
type Config struct {
	// PackagePath — import path пакета-источника.
	PackagePath string
	// InterfaceName — имя интерфейса в пакете.
	InterfaceName string
	// Dir — рабочий каталог для packages.Load: import path резолвится в
	// контексте модуля, находящегося в этом каталоге. Пусто — контекст
	// текущего модуля.
	Dir string
	// InPackage — мок в том же пакете, что и источник.
	InPackage bool
	// SourceInterface — имя интерфейса-источника при source-interface (может отличаться от InterfaceName).
	SourceInterface string
	// Source — go|test|all (§3.3); пусто — go.
	Source string
	// BuildTags — теги сборки для загрузки пакета.
	BuildTags []string
}

// InterfaceInfo — интерфейс, объявленный в пакете (для селекции all/include/exclude).
type InterfaceInfo struct {
	// Name — имя интерфейса.
	Name string
	// Exported — имя экспортировано.
	Exported bool
	// IsConstraint — constraint-интерфейс (~int | A|B): мокается с предупреждением-пропуском (§3.3).
	IsConstraint bool
	// Disabled — помечен директивой //neomock:generate=false (§4.5).
	Disabled bool
	// File — файл объявления.
	File string
}

// PackageInfo — загруженный пакет для селекции интерфейсов (§3.3).
type PackageInfo struct {
	// PkgPath — import path пакета.
	PkgPath string
	// Name — имя пакета в исходниках.
	Name string
	// Dir — каталог исходников пакета (абсолютный путь).
	Dir string
	// ModuleDir — корень содержащего модуля; пусто для GOROOT/без модуля.
	ModuleDir string
	// InModule — пакет внутри текущего модуля (иначе GOROOT/module cache).
	InModule bool
	// Interfaces — интерфейсы пакета без generated-файлов, отсортированы по имени.
	Interfaces []InterfaceInfo
	// Warnings — предупреждения загрузчика (source:test для внешнего пакета).
	Warnings []string
}

// Load загружает интерфейс и строит model.Interface.
// Возвращает ошибку, если пакет не загрузился, тип не найден или не интерфейс.
func Load(cfg Config) (*model.Interface, error) {
	if cfg.InterfaceName == "" {
		return nil, fmt.Errorf("loader: InterfaceName обязателен")
	}
	if cfg.PackagePath == "" {
		return nil, fmt.Errorf("loader: PackagePath обязателен")
	}
	source, err := normalizeSource(cfg.Source)
	if err != nil {
		return nil, err
	}

	pkgs, err := packages.Load(loadConfig(cfg, source), cfg.PackagePath)
	if err != nil {
		return nil, fmt.Errorf("loader: packages.Load: %w", err)
	}
	vars, warnings, err := selectVariants(pkgs, cfg.PackagePath, source)
	if err != nil {
		return nil, err
	}
	_ = warnings // предупреждения отдаёт LoadPackage; здесь они не критичны

	lookupName := cfg.InterfaceName
	if cfg.SourceInterface != "" {
		lookupName = cfg.SourceInterface
	}

	var pkgErrors []string
	for _, p := range vars {
		if len(pkgErrors) == 0 {
			for _, e := range p.Errors {
				pkgErrors = append(pkgErrors, e.Msg)
			}
		}
		if p.Types == nil || p.Types.Scope() == nil {
			continue
		}
		obj := p.Types.Scope().Lookup(lookupName)
		if obj == nil {
			continue
		}
		if generatedPos(p, obj.Pos()) {
			continue // сгенерированный файл — не источник (§3.3)
		}
		named, ok := types.Unalias(obj.Type()).(*types.Named)
		if !ok {
			return nil, fmt.Errorf(
				"loader: %q не является именованным типом в пакете %q",
				lookupName,
				cfg.PackagePath,
			)
		}
		iface, err := model.FromNamed(named)
		if err != nil {
			return nil, fmt.Errorf("loader: %w", err)
		}
		fillPkgInfo(iface, p)
		if isConstraint(iface.IFace) {
			return nil, fmt.Errorf(
				"loader: интерфейс %q является constraint-интерфейсом — мокирование невозможно (§3.3)",
				lookupName,
			)
		}
		return iface, validatePrivacy(cfg, iface)
	}

	if len(pkgErrors) > 0 {
		return nil, fmt.Errorf(
			"loader: ошибки пакета %q: %s",
			cfg.PackagePath,
			joinMsgs(pkgErrors),
		)
	}
	hint := ""
	if source == SourceGo {
		hint = " (если интерфейс объявлен в *_test.go — установите source:test|all, §3.3/С4)"
	}
	return nil, fmt.Errorf(
		"loader: тип %q не найден в пакете %q%s",
		lookupName,
		cfg.PackagePath,
		hint,
	)
}

// LoadPackage загружает пакет и перечисляет объявленные в нём интерфейсы —
// вход для селекции all/include/exclude/interfaces (§3.3).
func LoadPackage(cfg Config) (*PackageInfo, error) {
	if cfg.PackagePath == "" {
		return nil, fmt.Errorf("loader: PackagePath обязателен")
	}
	source, err := normalizeSource(cfg.Source)
	if err != nil {
		return nil, err
	}
	pkgs, err := packages.Load(loadConfig(cfg, source), cfg.PackagePath)
	if err != nil {
		return nil, fmt.Errorf("loader: packages.Load: %w", err)
	}
	vars, warnings, err := selectVariants(pkgs, cfg.PackagePath, source)
	if err != nil {
		return nil, err
	}

	info := &PackageInfo{PkgPath: cfg.PackagePath, Warnings: warnings}
	seen := map[string]bool{}
	for _, p := range vars {
		if len(p.Errors) > 0 {
			// ошибки типов пакета — наверх, молчаливая генерация запрещена
			msgs := make([]string, 0, len(p.Errors))
			for _, e := range p.Errors {
				msgs = append(msgs, e.Msg)
			}
			return nil, fmt.Errorf(
				"loader: ошибки пакета %q: %s",
				cfg.PackagePath,
				joinMsgs(msgs),
			)
		}
		if info.Name == "" {
			info.Name = p.Name
		}
		if p.Dir != "" {
			info.Dir = p.Dir
		}
		if p.Module != nil {
			info.InModule = info.InModule || p.Module.Main
			if p.Module.Main && info.ModuleDir == "" {
				info.ModuleDir = p.Module.Dir
			}
		}
		disabled := disabledTypes(p)
		for _, name := range p.Types.Scope().Names() {
			tn, ok := p.Types.Scope().Lookup(name).(*types.TypeName)
			if !ok || seen[name] {
				continue
			}
			if generatedPos(p, tn.Pos()) {
				continue
			}
			named, ok := types.Unalias(tn.Type()).(*types.Named)
			if !ok {
				continue
			}
			iface, ok := named.Underlying().(*types.Interface)
			if !ok {
				continue
			}
			seen[name] = true
			info.Interfaces = append(info.Interfaces, InterfaceInfo{
				Name:         name,
				Exported:     token.IsExported(name),
				IsConstraint: isConstraint(iface),
				Disabled:     disabled[name],
				File:         p.Fset.Position(tn.Pos()).Filename,
			})
		}
	}
	sort.Slice(
		info.Interfaces,
		func(a, b int) bool { return info.Interfaces[a].Name < info.Interfaces[b].Name },
	)
	return info, nil
}

// hasTestFiles сообщает, включает ли вариант пакета *_test.go файлы.
func hasTestFiles(p *packages.Package) bool {
	for _, f := range p.GoFiles {
		if strings.HasSuffix(f, "_test.go") {
			return true
		}
	}
	return false
}

// normalizeSource приводит и валидирует значение source (§4.2).
func normalizeSource(s string) (string, error) {
	switch s {
	case "", SourceGo:
		return SourceGo, nil
	case SourceTest, SourceAll:
		return s, nil
	default:
		return "", fmt.Errorf("loader: source %q: допустимы go|test|all", s)
	}
}

// loadConfig собирает packages.Config под режим source: Tests:true нужен для
// test/all; для внешнего пакета тест-вариантов нет (§3.3).
func loadConfig(cfg Config, source string) *packages.Config {
	return &packages.Config{
		Dir: cfg.Dir,
		Mode: packages.NeedName | packages.NeedFiles |
			packages.NeedTypes | packages.NeedTypesInfo |
			packages.NeedSyntax | packages.NeedDeps |
			packages.NeedModule,
		Tests:      source != SourceGo,
		BuildFlags: buildFlags(cfg.BuildTags),
	}
}

func buildFlags(tags []string) []string {
	if len(tags) == 0 {
		return nil
	}
	return []string{"-tags", strings.Join(tags, ",")}
}

// selectVariants возвращает варианты пакета в порядке поиска (§3.3):
// go — базовый; test — внутренний и внешний тест-варианты; all — все с дедупом.
// Для пакета вне модуля source:test|all трактуется как go с предупреждением.
//
// go/packages возвращает: базовый пакет (PkgPath == pkgPath, без *_test.go),
// внутренний тест-вариант (тот же PkgPath, но с *_test.go; в некоторых
// версиях toolchain с суффиксом " [pkg.test]"), внешний тест-пакет
// (PkgPath == pkgPath+"_test") и main-пакет тест-бинарника "pkg.test" (не нужен).
func selectVariants(
	pkgs []*packages.Package,
	pkgPath,
	source string,
) ([]*packages.Package, []string, error) {
	var base, internal, external *packages.Package
	for _, p := range pkgs {
		pp := p.PkgPath
		bracket := false
		if i := strings.Index(pp, " ["); i >= 0 {
			pp, bracket = pp[:i], true
		}
		switch pp {
		case pkgPath:
			if bracket || hasTestFiles(p) {
				internal = p
			} else {
				base = p
			}
		case pkgPath + "_test":
			external = p
		}
	}
	if base == nil && internal == nil && external == nil {
		return nil, nil, fmt.Errorf("loader: пакет %q не найден", pkgPath)
	}
	// Пакет без исходников (cgo-only, только бинарные данные) — §3.3.
	if base != nil && len(base.GoFiles) == 0 && len(base.Errors) > 0 {
		return nil, nil, fmt.Errorf(
			"loader: нет исходников для %q, мок невозможен: %s",
			pkgPath,
			joinErrs(base.Errors),
		)
	}

	var warnings []string
	inModule := base != nil && base.Module != nil && base.Module.Main
	if source != SourceGo && !inModule {
		warnings = append(warnings, fmt.Sprintf(
			"loader: пакет %q вне текущего модуля — тестовые файлы недоступны, source:%s трактуется как go (§3.3)", pkgPath, source))
		source = SourceGo
	}

	var out []*packages.Package
	switch source {
	case SourceTest:
		for _, p := range []*packages.Package{internal, external} {
			if p != nil {
				out = append(out, p)
			}
		}
		if len(out) == 0 {
			return nil, warnings, fmt.Errorf(
				"loader: интерфейс не найден в тестовых файлах пакета %q (source:test)",
				pkgPath,
			)
		}
	case SourceAll:
		for _, p := range []*packages.Package{base, internal, external} {
			if p != nil {
				out = append(out, p)
			}
		}
	default:
		if base != nil {
			out = append(out, base)
		}
	}
	return out, warnings, nil
}

// fillPkgInfo дополняет model.Interface фактами о пакете из go/packages:
// каталог исходников и принадлежность текущему модулю (placement rules, §3.3).
func fillPkgInfo(iface *model.Interface, p *packages.Package) {
	iface.Pkg.Dir = p.Dir
	iface.Pkg.InModule = p.Module != nil && p.Module.Main
}

// generatedPos сообщает, объявлен ли объект в файле с маркером neomock (§3.3).
func generatedPos(p *packages.Package, pos token.Pos) bool {
	if !pos.IsValid() || p.Fset == nil {
		return false
	}
	filename := p.Fset.Position(pos).Filename
	return isGeneratedFile(filename)
}

// isGeneratedFile читает начало файла и ищет маркер генерации.
func isGeneratedFile(filename string) bool {
	if filename == "" {
		return false
	}
	f, err := os.Open(filename)
	if err != nil {
		return false
	}
	defer func() { _ = f.Close() }()
	sc := bufio.NewScanner(f)
	for i := 0; sc.Scan() && i < 5; i++ {
		if strings.Contains(sc.Text(), GeneratedMarker) {
			return true
		}
	}
	return false
}

// disabledTypes находит имена типов с директивой //neomock:generate=false (§4.5).
func disabledTypes(p *packages.Package) map[string]bool {
	out := map[string]bool{}
	for _, file := range p.Syntax {
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				doc := gd.Doc
				if doc == nil {
					doc = ts.Doc
				}
				if doc != nil && hasDirective(doc) {
					out[ts.Name.Name] = true
				}
			}
		}
	}
	return out
}

// hasDirective ищет директиву в сырых комментариях: CommentGroup.Text()
// отбрасывает directive-подобные комментарии (//name:value), поэтому
// проверяем исходный список.
func hasDirective(doc *ast.CommentGroup) bool {
	for _, c := range doc.List {
		if strings.Contains(c.Text, directiveDisable) {
			return true
		}
	}
	return false
}

// isConstraint сообщает, является ли интерфейс constraint-интерфейсом
// (тип-множество содержит не-интерфейсные члены: ~int, int|string, comparable).
func isConstraint(iface *types.Interface) bool {
	for k := 0; k < iface.NumEmbeddeds(); k++ {
		if nonInterfaceTerm(iface.EmbeddedType(k)) {
			return true
		}
	}
	return false
}

func nonInterfaceTerm(t types.Type) bool {
	switch x := types.Unalias(t).(type) {
	case *types.Interface:
		return isConstraint(x)
	case *types.Union:
		return true
	case *types.Named:
		// comparable — встроенный constraint: underlying — пустой интерфейс,
		// тип-множество не пустое, но go/types не даёт его инспектировать.
		if x.Obj().Pkg() == nil && x.Obj().Name() == "comparable" {
			return true
		}
		if u, ok := x.Underlying().(*types.Interface); ok {
			return isConstraint(u)
		}
		return true
	default:
		return true
	}
}

// validatePrivacy — валидация приватности (§3.3): unexported-имя интерфейса
// недоступно из чужого пакета — мок возможен только при inpackage.
// Unexported-МЕТОДЫ разрешены и без inpackage (§3.4): эмиттер автовстраивает
// исходный интерфейс в структуру мока (gRPC-стиль).
func validatePrivacy(cfg Config, iface *model.Interface) error {
	if !iface.Exported && !cfg.InPackage {
		return fmt.Errorf(
			"loader: интерфейс %q неэкспортирован — мок возможен только при inpackage",
			cfg.InterfaceName,
		)
	}
	return nil
}

func joinMsgs(msgs []string) string {
	return strings.Join(msgs, "; ")
}

func joinErrs(errs []packages.Error) string {
	msgs := make([]string, 0, len(errs))
	for _, e := range errs {
		msgs = append(msgs, e.Error())
	}
	return joinMsgs(msgs)
}
